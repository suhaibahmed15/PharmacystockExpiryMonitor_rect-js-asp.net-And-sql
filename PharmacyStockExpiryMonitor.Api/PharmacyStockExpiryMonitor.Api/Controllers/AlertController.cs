using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using PharmacyStockExpiryMonitor.Api.DTOs.Alert;
using PharmacyStockExpiryMonitor.Api.Services.Interfaces;

namespace PharmacyStockExpiryMonitor.Api.Controllers
{
    [Route("api/[controller]")]
    [ApiController]
    [Authorize]
    public class AlertController : ControllerBase
    {
        private readonly IAlertService _alertService;

        public AlertController(IAlertService alertService)
        {
            _alertService = alertService;
        }

        // GET: api/Alert
        // Gets all alerts generated by the system.
        [HttpGet]
        public async Task<IActionResult> GetAll()
        {
            var alerts = await _alertService.GetAllAsync();

            return Ok(alerts);
        }

        // GET: api/Alert/5
        // Gets one alert by its ID.
        [HttpGet("{id}")]
        public async Task<IActionResult> GetById(int id)
        {
            var alert = await _alertService.GetByIdAsync(id);

            if (alert == null)
                return NotFound(new { message = "Alert not found." });

            return Ok(alert);
        }

        // PUT: api/Alert/5/read
        // Marks an alert as read.
        [HttpPut("{id}/read")]
        public async Task<IActionResult> MarkAsRead(int id)
        {
            var result = await _alertService.MarkAsReadAsync(id);

            if (!result)
                return NotFound(new { message = "Alert not found." });

            return Ok(new
            {
                message = "Alert marked as read."
            });
        }

        // PUT: api/Alert/5/resolve
        // Marks an alert as resolved.
        [HttpPut("{id}/resolve")]
        public async Task<IActionResult> Resolve(int id)
        {
            var result = await _alertService.ResolveAsync(id);

            if (!result)
                return NotFound(new { message = "Alert not found." });

            return Ok(new
            {
                message = "Alert resolved successfully."
            });
        }

        // POST: api/Alert
        // Creates a new alert for a medicine or batch.
        [HttpPost]
        public async Task<IActionResult> Create(AlertDto dto)
        {
            var alert = await _alertService.CreateAsync(
                dto.MedicineId,
                dto.BatchId,
                dto.AlertType,
                dto.Message);

            return CreatedAtAction(
                nameof(GetById),
                new { id = alert.Id },
                alert);
        }
    }
}